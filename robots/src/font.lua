local function glyph(ch)
  local u = ch:upper()
  return GLYPHS[u] or GLYPHS[ch] or GLYPHS["?"]
end

function Font.measure(text, scale)
  scale = scale or 1
  return #text * 8 * scale, 8 * scale
end

function Font.print(text, x, y, color, scale)
  scale = scale or 1
  if color then love.graphics.setColor(color) end
  text = tostring(text or "")
  local px, py = x, y
  for i = 1, #text do
    local ch = text:sub(i, i)
    if ch == "\n" then
      px = x
      py = py + 8 * scale
    else
      local rows = glyph(ch)
      for row = 0, 7 do
        local bits = rows[row + 1]
        for col = 0, 7 do
          if math.floor(bits / (2 ^ (7 - col))) % 2 == 1 then
            love.graphics.rectangle("fill", px + col * scale, py + row * scale, scale, scale)
          end
        end
      end
      px = px + 8 * scale
    end
  end
end

function Font.printf(text, x, y, w, color, scale)
  scale = scale or 1
  local maxChars = math.max(1, math.floor(w / (8 * scale)))
  local line, cx, cy = "", x, y
  local function flush()
    if #line > 0 then
      Font.print(line, cx, cy, color, scale)
      cy = cy + 9 * scale
      line = ""
    else
      cy = cy + 9 * scale
    end
  end
  for word in (text .. " "):gmatch("([^ ]*) ") do
    if word == "" then
      -- skip extra
    elseif #line == 0 then
      if #word > maxChars then
        for i = 1, #word, maxChars do
          Font.print(word:sub(i, i + maxChars - 1), cx, cy, color, scale)
          cy = cy + 9 * scale
        end
      else
        line = word
      end
    elseif #line + 1 + #word <= maxChars then
      line = line .. " " .. word
    else
      Font.print(line, cx, cy, color, scale)
      cy = cy + 9 * scale
      line = word
    end
  end
  if #line > 0 then
    Font.print(line, cx, cy, color, scale)
    cy = cy + 9 * scale
  end
  return cy
end

return Font
