--- The font, drawn by hand.
---
--- Five pixels wide in a six-pixel cell, eight rows tall, which is the shape
--- MSX2 used for `SCREEN 0: WIDTH 80`. At 480x270 that is exactly eighty
--- columns by thirty rows -- a 1985 terminal, to the character -- which is the
--- size the client drew into when the face was cut, and the proportion
--- everything is still laid out in.
---
--- Each glyph is eight rows separated by `/`; `#` is ink and `.` is paper.
--- Rows six and seven are where letters sit, so `g p q y j ,` can drop a tail
--- into row eight without colliding with the line below, which gets a
--- pixel of leading from `LINE` being nine.
---
--- Written out rather than loaded from a PNG because a PNG is not reviewable,
--- and because a font you can edit in the same buffer as the code that draws
--- it is a font that gets fixed.

