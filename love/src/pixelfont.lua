--- Expand one pattern into a list of rows of booleans.
function M.rows(pattern)
  local rows = {}
  for row in (pattern .. "/"):gmatch("([^/]*)/") do
    if #row > 0 then rows[#rows + 1] = row end
  end
  return rows
end

return M
